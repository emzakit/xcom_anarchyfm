def sync_ini_files(toggles, config_folder=None, has_tracks=None, pack_defs=None,
                   mod_config_dirs=None):
    """Rewrite all three MMS config files based on current toggle states.

    Args:
        toggles: dict mapping toggle keys to bool, e.g.
                 {"shell_menu": True, "avenger": True, "battle": False, ...}
        config_folder: path to the game's user Config directory.
                       Only needed on first call; cached after that.
        has_tracks: dict mapping the same toggle keys to whether that state
                    resolves to any playable audio. A state with none is left
                    unsilenced so MMS can cover it — see the module docstring.
                    Omit to silence purely on toggles.
        pack_defs: {toggle key: [definition ids]} for enabled third-party MMS
                   music packs, from mms_packs.find_pack_defs(). Their
                   definitions are registered as fallbacks on the states we
                   cover, so MMS stops choosing between them and us at random.
    """
    global _config_dir

    if config_folder:
        _config_dir = config_folder

    if not _config_dir:
        console.warn("MMS config: no config directory set (need log_path on first call).")
        return

    if not os.path.isdir(_config_dir):
        console.warn(f"MMS config dir not found: {_config_dir}")
        return

    changes = []

    # Shell
    shell_path = os.path.join(_config_dir, "XComShellSound.ini")
    shell_content = _build_shell_ini(_reason("shell_menu", toggles, has_tracks),
                                     pack_defs)
    if _write_if_changed(shell_path, shell_content):
        changes.append("shell")

    # Strategy
    strat_path = os.path.join(_config_dir, "XComStrategySound.ini")
    strat_content = _build_strategy_ini(toggles, has_tracks, pack_defs)
    if _write_if_changed(strat_path, strat_content):
        changes.append("strategy")

    # Tactical
    tact_path = os.path.join(_config_dir, "XComTacticalSound.ini")
    tact_content = _build_tactical_ini(_reason("battle", toggles, has_tracks),
                                       pack_defs)
    if _write_if_changed(tact_path, tact_content):
        changes.append("tactical")

    # The copies that actually get read. MMS loads config from each mod's own
    # Config folder; the game never mirrors mod config files into the user's
    # Documents config directory, so the writes above are kept only because
    # they are harmless and long-standing. Everything downstream of MMS
    # depends on these.
    written_to_mod = 0
    for mod_dir in (mod_config_dirs or []):
        if not os.path.isdir(mod_dir):
            continue
        _write_if_changed(os.path.join(mod_dir, "XComShellSound.ini"), shell_content)
        _write_if_changed(os.path.join(mod_dir, "XComStrategySound.ini"), strat_content)
        _write_if_changed(os.path.join(mod_dir, "XComTacticalSound.ini"), tact_content)
        written_to_mod += 1

    if not written_to_mod:
        # Loud, because the failure is otherwise invisible: the app plays its
        # music perfectly and the game plays straight over the top of it.
        console.error("Can't find the installed Anarchy Radio FM mod folder — "
                      "the game's own music will NOT be silenced.")
        console.shen("Set \"workshop_folder\" in xipod_config.json (or "
                     "\"mod_config_folder\" for a non-Workshop install), "
                     "then restart me.")

    if changes:
        console.signal(f"MMS config updated: {', '.join(changes)} — takes effect on next game launch.")
    else:
        console.debug("MMS config: no changes needed.")


def _write_if_changed(path, content):
    """Write file only if content differs. Returns True if written."""
    try:
        if os.path.exists(path):
            with open(path, 'r', encoding='utf-8') as f:
                existing = f.read()
            if existing == content:
                return False
    except Exception:
        pass  # If we can't read, just write

    try:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        return True
    except Exception as e:
        console.warn(f"Failed to write {path}: {e}")
        return False
